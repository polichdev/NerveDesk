    inline void CalculateEdidChecksum(BYTE* edid, size_t size)
    {
        if (size < 128) return;
        BYTE sum = 0;
        for (size_t i = 0; i < 127; ++i)
        {
            sum += edid[i];
        }
        edid[127] = static_cast<BYTE>((256 - (sum % 256)) % 256);
    }
